import { chromium } from 'playwright-core'
import { ARQUIVOS, CHROME, ENV_JAVA, PLANILHA_PROFESSOR, RAIZ } from './config.mjs'
import { readFileSync } from 'node:fs'
const env = Object.fromEntries(readFileSync(ENV_JAVA,'utf8').split(/\r?\n/).filter(l=>l.includes('=')&&!l.startsWith('#')).map(l=>[l.slice(0,l.indexOf('=')).trim(),l.slice(l.indexOf('=')+1).trim()]))
const out = process.argv[2] || `${RAIZ}/testes/navegador/saida`, B='http://localhost:5173'
let ok=0, falha=0; const confere=(n,c,d='')=>{c?ok++:falha++; console.log(`[${c?'OK   ':'FALHA'}] ${n} ${d}`)}
const b = await chromium.launch({ executablePath:CHROME })
const p = await b.newPage({ viewport:{ width:1366, height:768 } })
const erros=[]; p.on('pageerror',e=>erros.push(e.message))
await p.goto(B+'/login'); await p.locator('input[type=email]').fill(env.ADMIN_EMAIL); await p.locator('input[type=password]').fill(env.ADMIN_PASSWORD)
await p.locator('button[type=submit]').click(); await p.waitForURL('**/dashboard'); await p.waitForTimeout(1500)

const rotulos = (await p.locator('aside nav a').allInnerTexts()).map(t=>t.trim())
confere('menu com "Clientes" no lugar de "Relatórios"', rotulos.includes('CLIENTES') || rotulos.includes('Clientes'), JSON.stringify(rotulos))
await p.mouse.wheel(0, 5000); await p.waitForTimeout(800)
const nav = await p.locator('aside nav').boundingBox(), sair = await p.getByRole('button',{name:'Sair do sistema'}).boundingBox()
confere('desktop: menu e "Sair" continuam visíveis ao rolar até o fim', nav.y >= 0 && sair.y + sair.height <= 768, `nav y=${Math.round(nav.y)} sair y=${Math.round(sair.y)}`)
await p.screenshot({ path:`${out}/sb2-desktop-rolado.png` })
const link = p.locator('aside nav a').nth(2)
const antes = await link.locator('span').first().evaluate(e=>getComputedStyle(e).backgroundColor)
await link.hover(); await p.waitForTimeout(400)
const depois = await link.locator('span').first().evaluate(e=>getComputedStyle(e).backgroundColor)
confere('passar o mouse muda o fundo do item', antes !== depois)
const corSair = await p.getByRole('button',{name:'Sair do sistema'}).evaluate(e=>getComputedStyle(e).color)
confere('"Sair" em cinza (não vermelho)', !/rgb\(2[0-9]{2}, [0-9]{1,2}, /.test(corSair) && !corSair.includes('0.637 0.237'), corSair)
await link.click(); await p.waitForURL('**/relatorios')
confere('link "Clientes" abre a tela de clientes', await p.getByRole('heading',{name:'Clientes', exact:true}).count() === 1)

// tablet
await p.setViewportSize({ width:700, height:900 }); await p.goto(B+'/dashboard'); await p.waitForTimeout(1500)
const legenda = await p.getByText('Indústria', { exact: true }).first().evaluate(e => e.scrollWidth <= e.clientWidth)
confere('tablet: legenda do gráfico sem nome cortado', legenda)
await p.screenshot({ path:`${out}/sb2-tablet.png` })
await p.mouse.wheel(0, 3000); await p.waitForTimeout(500)
const navT = await p.locator('aside nav').boundingBox()
confere('tablet: ícones continuam visíveis ao rolar', navT.y >= 0, `y=${Math.round(navT.y)}`)

// celular
await p.setViewportSize({ width:390, height:844 }); await p.goto(B+'/dashboard'); await p.waitForTimeout(1200)
await p.mouse.wheel(0, 1500); await p.waitForTimeout(400)
const botao = p.getByRole('button',{name:/abrir menu/i})
const bb = await botao.boundingBox()
confere('celular: hambúrguer continua no topo ao rolar', bb && bb.y >= 0 && bb.y < 70, `y=${bb && Math.round(bb.y)}`)
const yConteudo = await p.evaluate(() => window.scrollY)
await botao.click(); await p.waitForTimeout(400)
confere('celular: menu abre por cima, sem empurrar a página', await p.evaluate(() => window.scrollY) === yConteudo && await p.locator('#menu-principal').isVisible())
await p.screenshot({ path:`${out}/sb2-celular-aberto.png` })
await p.mouse.click(200, 780); await p.waitForTimeout(400)
confere('celular: tocar fora fecha o menu', !(await p.locator('#menu-principal').isVisible()))
await botao.click(); await p.waitForTimeout(300)
await p.keyboard.press('Escape'); await p.waitForTimeout(300)
confere('celular: Esc fecha o menu', !(await p.locator('#menu-principal').isVisible()))
await botao.click(); await p.waitForTimeout(300)
await p.locator('#menu-principal').getByRole('link',{name:/Clientes/}).click(); await p.waitForURL('**/relatorios'); await p.waitForTimeout(300)
confere('celular: escolher uma tela navega e fecha o menu', !(await p.locator('#menu-principal').isVisible()))
await p.getByRole('button',{name:/abrir menu/i}).click(); await p.waitForTimeout(300)
await p.locator('#menu-principal').getByRole('button',{name:'Sair do sistema'}).click(); await p.waitForURL('**/login')
confere('celular: "Sair" dentro do menu encerra a sessão', p.url().includes('/login'))
confere('sem erros de JavaScript', erros.length===0, erros.join(' | '))
await b.close(); console.log(`\nResumo: ${ok} OK, ${falha} FALHA`)
