import { chromium } from 'playwright-core'
import { ARQUIVOS, CHROME, ENV_JAVA, PLANILHA_PROFESSOR, RAIZ } from './config.mjs'
import { readFileSync } from 'node:fs'
const env = Object.fromEntries(readFileSync(ENV_JAVA,'utf8').split(/\r?\n/).filter(l=>l.includes('=')&&!l.startsWith('#')).map(l=>[l.slice(0,l.indexOf('=')).trim(),l.slice(l.indexOf('=')+1).trim()]))
const out = process.argv[2] || `${RAIZ}/testes/navegador/saida`, B='http://localhost:5173'
let ok=0,falha=0; const confere=(n,c,d='')=>{c?ok++:falha++; console.log(`[${c?'OK   ':'FALHA'}] ${n} ${d}`)}
const b = await chromium.launch({ executablePath:CHROME })
const p = await b.newPage({ viewport:{ width:1366, height:900 } }); const erros=[]; p.on('pageerror',e=>erros.push(e.message))
await p.goto(B+'/login'); await p.locator('input[type=email]').fill(env.ADMIN_EMAIL); await p.locator('input[type=password]').fill(env.ADMIN_PASSWORD)
await p.locator('button[type=submit]').click(); await p.waitForURL('**/dashboard'); await p.waitForTimeout(2500)
const main = async () => (await p.locator('main').innerText()).replace(/\s+/g,' ')
const m = await main()
confere('mostra a origem dos dados', /Base: dados\.xlsx · 26\/11\/2026 às \d\d:\d\d por Simone Queiroz/.test(m), m.match(/Base:[^·]+·[^·]+?Queiroz/)?.[0])
const segs = await p.locator('select').first().locator('option').allInnerTexts()
confere('segmentos em ordem alfabética', JSON.stringify(segs.slice(1)) === JSON.stringify([...segs.slice(1)].sort((a,b)=>a.localeCompare(b,'pt-BR'))), segs.slice(1).join(', '))
confere('sem filtro, sem aviso nos insights', !/carteira inteira/.test(m))
confere('Top 10 no lugar da tabela paginada', /Top 10 clientes por faturamento/.test(m) && !/Página 1 de/.test(m))
const fat = (await p.locator('table').last().locator('tbody tr td:nth-child(5)').allInnerTexts()).map(t=>Number(t.replace(/[^\d,]/g,'').replace(',','.')))
confere('Top 10 em ordem de faturamento', fat.length === 10 && fat.every((v,i)=>i===0||fat[i-1]>=v), `${fat[0]} … ${fat.at(-1)}`)
await p.locator('select').first().selectOption('Saúde'); await p.waitForTimeout(600)
const m2 = await main()
confere('com filtro, aviso de que os insights são da carteira inteira', /carteira inteira/.test(m2))
confere('Top 10 acompanha o filtro (4 clientes de Saúde)', (await p.locator('table').last().locator('tbody tr').count()) === 4)
await p.screenshot({ path:`${out}/d2-filtro.png`, fullPage:true })
await p.locator('select').first().selectOption({ index:0 }); await p.waitForTimeout(500)
await p.getByRole('heading',{name:/Distribuição por nível/}).locator('xpath=..').screenshot({ path:`${out}/d2-nivel.png` })
await p.getByRole('heading',{name:/Evolução/}).locator('xpath=..').screenshot({ path:`${out}/d2-evol.png` })
await p.getByRole('link',{name:'Ver todos em Clientes →'}).click(); await p.waitForURL('**/relatorios')
confere('link "Ver todos em Clientes" leva à tela Clientes', p.url().endsWith('/relatorios'))
await p.goBack(); await p.waitForTimeout(2000)
await p.emulateMedia({ media:'print' }); await p.waitForTimeout(500)
await p.screenshot({ path:`${out}/d2-print.png`, fullPage:true })
confere('PDF sem o link de navegação', !(await p.getByRole('link',{name:'Ver todos em Clientes →'}).isVisible()))
confere('sem erros de JavaScript', erros.length===0, erros.join(' | '))
await b.close(); console.log(`\nResumo: ${ok} OK, ${falha} FALHA`)
